"""File storage with strict path containment.

Files are stored under ``<data>/storage/users/<user id>/projects/<project id>/``.
Storage keys are generated by the server from UUIDs; user-supplied names are
never used as paths. Every key is still validated and resolved, and anything
that would escape the storage root is rejected (path traversal protection).

Only local storage ships today. The small interface below is what an
S3-compatible backend would implement.

In hybrid mode the server never stores video: the same keys are tracked in the
database while the bytes live under the same layout on the user's worker. The
server's storage object is then created with ``remote=True`` and :meth:`has`
answers from the recorded key instead of the disk.
"""

from __future__ import annotations

import os
import re
import shutil
from pathlib import Path

_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]*$")


class StorageError(Exception):
    pass


class LocalStorage:
    def __init__(self, root: Path, *, remote: bool = False) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        #: True on a hybrid-mode server: files live on the owner's worker, not here.
        self.remote = remote

    def has(self, key: str | None) -> bool:
        """Is this file available to its owner (on this disk, or on their worker)?"""
        if self.remote:
            return bool(key)
        return self.exists(key)

    @staticmethod
    def user_prefix(user_id: str) -> str:
        return f"users/{user_id}"

    @staticmethod
    def project_prefix(user_id: str, project_id: str) -> str:
        return f"users/{user_id}/projects/{project_id}"

    def path(self, key: str) -> Path:
        """Resolve a storage key to an absolute path inside the storage root."""
        if not key or not _KEY_RE.match(key) or "\\" in key:
            raise StorageError("Invalid storage key.")
        parts = key.split("/")
        if any(part in {"", ".", ".."} for part in parts):
            raise StorageError("Invalid storage key.")
        resolved = (self.root / key).resolve()
        if resolved == self.root or not resolved.is_relative_to(self.root):
            raise StorageError("Storage key escapes the storage root.")
        return resolved

    def ensure_parent(self, key: str) -> Path:
        path = self.path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        return path

    def exists(self, key: str | None) -> bool:
        if not key:
            return False
        try:
            return self.path(key).is_file()
        except StorageError:
            return False

    def size(self, key: str) -> int:
        return self.path(key).stat().st_size

    def delete(self, key: str | None) -> None:
        if not key:
            return
        path = self.path(key)
        if path.is_file():
            path.unlink()

    def delete_tree(self, prefix: str) -> None:
        path = self.path(prefix)
        if path.is_dir():
            shutil.rmtree(path)

    def usage_bytes(self, prefix: str) -> int:
        path = self.path(prefix)
        if not path.is_dir():
            return 0
        total = 0
        for dirpath, _dirnames, filenames in os.walk(path):
            for filename in filenames:
                try:
                    total += (Path(dirpath) / filename).stat().st_size
                except OSError:
                    continue
        return total
