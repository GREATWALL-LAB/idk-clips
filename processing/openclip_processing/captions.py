"""Burned-in caption rendering via ASS subtitles (drawn by FFmpeg's libass).

Caption text comes from the real transcript (or from the user's own edits); it is
never generated by AI. Word-by-word highlighting uses Whisper's word timestamps.
"""

from __future__ import annotations

import re
import shutil
import struct
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

FONTS_DIR = Path(__file__).parent / "assets" / "fonts"

#: Font family names as stored inside the bundled TTF files (all SIL Open Font License).
FONT_FILES = {
    "Montserrat": "Montserrat-Bold.ttf",
    "Poppins": "Poppins-Bold.ttf",
    "Anton": "Anton-Regular.ttf",
}

#: Font sizes are CSS pixels on a 1080-pixel-wide vertical frame; other frames scale
#: with their shorter side, so captions look the same in 9:16, 4:5, 1:1 and 16:9.
REFERENCE_SHORT_SIDE = 1080


@lru_cache
def font_cell_ratio(font: str) -> float:
    """(winAscent + winDescent) / unitsPerEm for a bundled font.

    libass sizes text by the font's full line height (Windows ascent + descent),
    while browsers size it by the em square. Multiplying by this ratio makes the
    burned-in captions match the editor preview and the size shown in the UI.
    """
    data = (FONTS_DIR / FONT_FILES[font]).read_bytes()
    (num_tables,) = struct.unpack(">H", data[4:6])
    offsets: dict[bytes, int] = {}
    for index in range(num_tables):
        tag, _checksum, offset, _length = struct.unpack(
            ">4sIII", data[12 + 16 * index : 28 + 16 * index]
        )
        offsets[tag] = offset
    head, os2 = offsets[b"head"], offsets[b"OS/2"]
    (units_per_em,) = struct.unpack(">H", data[head + 18 : head + 20])
    win_ascent, win_descent = struct.unpack(">HH", data[os2 + 74 : os2 + 78])
    return (win_ascent + win_descent) / units_per_em


_OVERRIDE_RE = re.compile(r"[{}\\]")


@dataclass
class CaptionCue:
    start: float  # seconds, relative to the clip start
    end: float
    text: str
    words: list[dict[str, Any]] | None = None  # relative word timings for highlighting


def ass_color(hex_rgb: str, alpha: int = 0) -> str:
    """'#RRGGBB' -> '&HAABBGGRR' (ASS stores colors as alpha, blue, green, red)."""
    value = hex_rgb.lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}", value):
        raise ValueError(f"Invalid color {hex_rgb!r}")
    red, green, blue = value[0:2], value[2:4], value[4:6]
    return f"&H{alpha:02X}{blue}{green}{red}".upper()


def ass_override_color(hex_rgb: str) -> str:
    """'#RRGGBB' -> '&HBBGGRR&' for inline \\c override tags."""
    value = ass_color(hex_rgb)[4:]  # drop "&HAA"
    return f"&H{value}&"


def ass_time(seconds: float) -> str:
    centiseconds = max(0, round(seconds * 100))
    hours, rest = divmod(centiseconds, 360_000)
    minutes, rest = divmod(rest, 6000)
    secs, cs = divmod(rest, 100)
    return f"{hours:d}:{minutes:02d}:{secs:02d}.{cs:02d}"


def clean_caption_text(text: str, uppercase: bool = False) -> str:
    """Remove characters that ASS would interpret as styling overrides."""
    cleaned = " ".join(_OVERRIDE_RE.sub("", text).split())
    return cleaned.upper() if uppercase else cleaned


def build_ass(
    cues: list[CaptionCue],
    style: dict[str, Any],
    *,
    width: int,
    height: int,
) -> str:
    font = style.get("font", "Montserrat")
    if font not in FONT_FILES:
        raise ValueError(f"Unsupported font {font!r}")
    scale = min(width, height) / REFERENCE_SHORT_SIDE
    size = max(12, round(int(style.get("font_size", 72)) * scale * font_cell_ratio(font)))
    outline = round(int(style.get("outline_width", 6)) * scale, 1)
    primary = ass_color(style.get("text_color", "#FFFFFF"))
    highlight = ass_color(style.get("highlight_color", "#FACC15"))
    highlight_tag = ass_override_color(style.get("highlight_color", "#FACC15"))
    outline_color = ass_color(style.get("outline_color", "#000000"))
    uppercase = bool(style.get("uppercase", False))
    if style.get("background"):
        border_style, outline_value = 3, max(6.0, size * 0.18)  # opaque box with padding
        box_color = ass_color(style.get("background_color", "#000000"), alpha=0x40)
        outline_color, back_color, shadow = box_color, box_color, 0
    else:
        border_style, outline_value = 1, outline
        back_color, shadow = ass_color("#000000", alpha=0x80), round(2 * scale, 1)
    position = style.get("position", "bottom")
    alignment = {"bottom": 2, "middle": 5, "top": 8}.get(position, 2)
    margin_v = {"bottom": round(height * 0.17), "middle": 0, "top": round(height * 0.12)}.get(
        position, 0
    )
    margin_h = round(width * 0.07)

    header = (
        "[Script Info]\n"
        "ScriptType: v4.00+\n"
        f"PlayResX: {width}\n"
        f"PlayResY: {height}\n"
        "WrapStyle: 0\n"
        "ScaledBorderAndShadow: yes\n"
        "YCbCr Matrix: TV.709\n\n"
        "[V4+ Styles]\n"
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
        "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, "
        "Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n"
        f"Style: Caption,{font},{size},{primary},{highlight},{outline_color},{back_color},"
        f"-1,0,0,0,100,100,0,0,{border_style},{outline_value},{shadow},{alignment},"
        f"{margin_h},{margin_h},{margin_v},1\n\n"
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    )

    events: list[str] = []
    highlight_words = bool(style.get("highlight_words", True))
    for cue in cues:
        text = clean_caption_text(cue.text, uppercase)
        if not text or cue.end <= cue.start:
            continue
        words = cue.words or []
        tokens = [clean_caption_text(str(w.get("text", "")), uppercase) for w in words]
        if highlight_words and words and " ".join(t for t in tokens if t) == text:
            # One event per spoken word, with the current word in the highlight color.
            if words[0]["start"] > cue.start + 0.02:
                events.append(_dialogue(cue.start, words[0]["start"], text))
            for index, word in enumerate(words):
                if not tokens[index]:
                    continue
                start = max(cue.start, float(word["start"]))
                end = float(words[index + 1]["start"]) if index + 1 < len(words) else cue.end
                end = min(max(end, start + 0.05), cue.end)
                parts = [
                    f"{{\\c{highlight_tag}}}{t}{{\\r}}" if i == index else t
                    for i, t in enumerate(tokens)
                    if t
                ]
                events.append(_dialogue(start, end, " ".join(parts)))
        else:
            events.append(_dialogue(cue.start, cue.end, text))
    return header + "\n".join(events) + ("\n" if events else "")


def _dialogue(start: float, end: float, text: str) -> str:
    return f"Dialogue: 0,{ass_time(start)},{ass_time(end)},Caption,,0,0,0,,{text}"


def copy_fonts(destination: Path) -> Path:
    """Copy the bundled fonts next to the subtitle file (libass loads them from there)."""
    destination.mkdir(parents=True, exist_ok=True)
    for filename in FONT_FILES.values():
        shutil.copy2(FONTS_DIR / filename, destination / filename)
    return destination
